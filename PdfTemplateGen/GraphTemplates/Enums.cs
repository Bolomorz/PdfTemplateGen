namespace PdfTemplateGen.GraphTemplates;

public enum VerticalDirection
{
    /// <summary>
    /// x-axis is on top
    /// </summary>
    FromTopToBot,
    /// <summary>
    /// x-axis is bottom
    /// </summary>
    FromBotToTop
}
public enum HorizontalDirection
{
    /// <summary>
    /// y-axis is left
    /// </summary>
    FromLeftToRight,
    /// <summary>
    /// y-axis is right
    /// </summary>
    FromRightToLeft
}